#!/usr/bin/env python3
"""Write src/replay.h from a compact input script, for frame-exact test runs.

Usage: python3 tools/replay.py "S*2 _*30 R*40 RB*20 _*60"
Each token is KEYS*FRAMES; '#' starts a comment that runs to the end of the line. Keys: L R U D B(jump) A(throw) S(start) _(none).
Build the replay binary with:  cmake -B build-replay -DREPLAY=ON && cmake --build build-replay
"""
import os, sys
BITS = {"B": 0x0001, "S": 0x0008, "U": 0x0010, "D": 0x0020, "L": 0x0040, "R": 0x0080, "A": 0x0100, "_": 0}
steps = []
text = "\n".join(l.split("#", 1)[0] for l in " ".join(sys.argv[1:]).splitlines())
for tok in text.split():
    keys, _, n = tok.partition("*")
    mask = 0
    for k in keys:
        mask |= BITS[k]
    steps.append((int(n or 1), mask))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "replay.h")
with open(out, "w") as f:
    f.write("/* generated by tools/replay.py (%d steps) */\n" % len(steps))
    f.write("static const uint16_t REPLAY_INPUT[][2] = {\n")
    for n, m in steps:
        f.write("    { %d, 0x%04x },\n" % (n, m))
    f.write("    { 0, 0 },\n};\n")
print("frames:", sum(n for n, _ in steps))
